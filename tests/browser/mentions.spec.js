const {test,expect}=require('@playwright/test');
test('typed mentions search users and issues in comments, replies and edits',async({page})=>{
  await page.goto('/');await page.getByRole('button',{name:'Enter workspace'}).click();
  await expect(page.locator('#page-title')).toBeVisible();
  await page.goto('/index.php/issues/17');
  const input=page.locator('#comment-body'), picker=page.getByRole('listbox',{name:'Mention suggestions'});
  await input.fill('email@example.com');await expect(picker).toBeHidden();
  await input.fill('Please check @jam');await expect(picker.getByRole('option')).toHaveCount(1);
  await expect(picker).toContainText('Jamie Chen');await input.press('Enter');
  await expect(input).toHaveValue('Please check @[Jamie Chen](user:2) ');await expect(picker).toBeHidden();
  await input.press('End');await input.pressSequentially('@ORB-017');
  await expect(picker.getByRole('option')).toHaveCount(1);await picker.getByRole('option').click();
  await expect(input).toHaveValue(/\(issue:17\)/);
  await page.locator('#comment-form [type=submit]').click();
  const comment=page.locator('.discussion-comment').filter({hasText:'Please check'}).last();
  await expect(comment.locator('.comment-text')).toContainText('@Jamie Chen');
  await expect(comment.locator('.comment-text a')).toHaveAttribute('href',/issues\/17$/);
  await page.reload();await expect(comment.locator('.comment-text')).toContainText('@Jamie Chen');
  await expect(comment.getByRole('button',{name:'Reply',exact:true})).toHaveCount(0);
  await page.locator('.discussion-comment').filter({hasText:'The initial profiling looks good'}).getByRole('button',{name:'Reply',exact:true}).click();
  const reply=page.getByLabel('Leave a reply',{exact:true});await reply.fill('@');await expect(picker).toContainText('Users');await expect(picker).toContainText('Issues');
  await reply.press('ArrowDown');await reply.press('Enter');await expect(reply).toHaveValue(/Jamie Chen/);
  await page.locator('[data-key^="reply-"] [data-action=cancel]').click();
  await comment.getByLabel('Comment actions').click();await comment.getByRole('button',{name:'Edit comment',exact:true}).click();
  const edit=comment.getByLabel('Edit comment',{exact:true});await edit.fill('@sam');await edit.press('Tab');await expect(edit).toHaveValue('@[Sam Rivera](user:3) ');
  await edit.fill('@no-such-person');await expect(picker).toContainText('No matches');await edit.press('Escape');await expect(picker).toBeHidden();
  await comment.getByRole('button',{name:'Cancel',exact:true}).click();
  await page.setViewportSize({width:390,height:844});await input.fill('@');await input.scrollIntoViewIfNeeded();await expect(picker).toBeVisible();
  const bounds=await picker.boundingBox();expect(bounds.x).toBeGreaterThanOrEqual(0);expect(bounds.x+bounds.width).toBeLessThanOrEqual(390);
  await page.screenshot({path:'build/screenshots/mentions-mobile.png'});
  await input.fill('');
});
