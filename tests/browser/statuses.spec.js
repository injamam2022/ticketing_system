const { test, expect } = require('@playwright/test');

test('staff can manage custom statuses across list, board and issue editing', async ({ page }) => {
  await page.goto('/index.php/statuses');
  await expect(page).toHaveURL(/login/);
  await page.getByRole('button', { name: 'Enter workspace' }).click();
  await page.getByRole('link', { name: 'Manage statuses' }).click();
  const add = page.locator('#add-status form');
  await add.locator('[name=name]').fill('Client "Approval"');
  await add.locator('[name=color]').fill('#00aabb');
  await add.locator('[name=category]').selectOption('review');
  await add.getByRole('button', { name: 'Add status', exact: true }).click();
  await expect(page.getByRole('status')).toHaveText('Statuses updated.');
  const card = page.locator('.status-card').filter({ hasText: 'Client "Approval"' });
  await card.locator('summary').click();
  await card.getByRole('button', { name: 'Move Client "Approval" up', exact: true }).click();
  await expect(page.locator('.status-card').nth(-2)).toContainText('Client "Approval"');
  await page.goto('/');
  await expect(page.locator('.issue-row').first()).toBeVisible();
  await page.locator('#main-create').click();
  await page.locator('#issue-title').fill('Custom status ticket');
  await page.locator('#edit-status').selectOption('Client "Approval"');
  await page.locator('#issue-form').getByRole('button', { name: 'Create issue', exact: true }).click();
  await expect(page.locator('.issue-row').filter({ hasText: 'Custom status ticket' })).toBeVisible();
  await page.locator('#filter-toggle').click();
  await page.locator('#status-filter').selectOption('Client "Approval"');
  await expect(page.locator('.issue-row')).toHaveCount(1);
  await page.locator('[data-layout=board]').click();
  await expect(page.locator('[data-drop-status]').filter({ hasText: 'Custom status ticket' })).toHaveAttribute('data-drop-status', 'Client "Approval"');
  await page.locator('.board-card').filter({ hasText: 'Custom status ticket' }).click();
  await expect(page.locator('#edit-status')).toHaveValue('Client "Approval"');
  await page.goto('/index.php/statuses');
  const edit = page.locator('.status-card').filter({ hasText: 'Client "Approval"' });
  await edit.locator('summary').click();
  await edit.locator('[name=name]').fill('Client approved');
  await edit.locator('[name=category]').selectOption('done');
  await edit.getByRole('button', { name: 'Save status' }).click();
  await page.goto('/');
  await page.locator('.board-card').filter({ hasText: 'Custom status ticket' }).click();
  await expect(page.locator('#edit-status')).toHaveValue('Client approved');
  const denied = await page.request.post('/index.php/statuses', { form: { name: 'Bad CSRF', color: '#123456', category: 'todo', csrf: 'invalid' } });
  expect(denied.status()).toBe(403);
});
